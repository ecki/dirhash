"""Generate validation tables from Unicode 16.0.0; no host Unicode dependency."""
import json
import urllib.request
from pathlib import Path

BASE = "https://www.unicode.org/Public/16.0.0/ucd/"

def get(name):
    return urllib.request.urlopen(BASE + name, timeout=60).read().decode("utf-8")

rows = [line.split(";") for line in get("UnicodeData.txt").splitlines()]
controls = []
combining = {}
decomp = {}
for row in rows:
    code = int(row[0], 16)
    if row[2] in ("Cc", "Cf"):
        controls.append(code)
    if int(row[3]):
        combining[code] = int(row[3])
    if row[5] and not row[5].startswith("<"):
        decomp[code] = [int(x, 16) for x in row[5].split()]
excluded = set()
for line in get("DerivedNormalizationProps.txt").splitlines():
    fields = line.split("#", 1)[0].strip().split(";")
    if len(fields) >= 2 and fields[1].strip() == "Full_Composition_Exclusion":
        bounds = fields[0].strip().split("..")
        excluded.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
folds = {}
for line in get("CaseFolding.txt").splitlines():
    fields = line.split("#", 1)[0].strip().split(";")
    if len(fields) >= 3 and fields[1].strip() in ("C", "F"):
        folds[int(fields[0], 16)] = "".join(chr(int(x, 16)) for x in fields[2].split())
ranges = []
for r in controls:
    if ranges and r == ranges[-1][1] + 1:
        ranges[-1][1] = r
    else:
        ranges.append([r, r])
lines = ["// Code generated by generate_unicode.py from Unicode 16.0.0 UCD. DO NOT EDIT.",
         "// https://www.unicode.org/license.txt", "package main",
         "var unicode16Controls = [][2]rune{"]
lines.extend("{0x%x,0x%x}," % tuple(pair) for pair in ranges)
lines.append("}\nvar unicode16Combining = map[rune]uint8{")
lines.extend("0x%x:%d," % item for item in combining.items())
lines.append("}\nvar unicode16Decompositions = map[rune][]rune{")
lines.extend("0x%x:{%s}," % (k, ",".join("0x%x" % r for r in v)) for k, v in decomp.items())
lines.append("}\nvar unicode16Compositions = map[[2]rune]rune{")
lines.extend("{0x%x,0x%x}:0x%x," % (*v, k) for k, v in decomp.items() if len(v) == 2 and k not in excluded)
lines.append("}\nvar unicode16Folds = map[rune]string{")
lines.extend("0x%x:%s," % (k, json.dumps(v, ensure_ascii=False)) for k, v in folds.items())
lines.append("}\n")
Path(__file__).with_name("unicode_tables.go").write_text("\n".join(lines), encoding="utf-8", newline="\n")
